export const GRADES = ['1-1', '1-2', '2-1', '2-2', '3-1', '3-2', '4-1', '4-2', '5-1', '5-2', '6-1', '6-2'];
export const gradeIdx = (g) => GRADES.indexOf(g);

// 이 문항(params)에서 내려갈 앞 개념
export function preOf(cid, p) {
  const c = byId[cid];
  if (!c) return [];
  const raw = typeof c.pre === 'function' ? c.pre(p) : c.pre || [];
  return [...new Set(raw.filter((x) => x && x !== cid && byId[x]))];
}

// 지도에 그릴 앞 개념 — 여러 문항을 만들어 보고 모두 합친다
const preCache = {};
export function allPre(cid) {
  if (preCache[cid]) return preCache[cid];
  const c = byId[cid], set = new Set(preOf(cid, null));
  if (typeof c.pre === 'function') {
    const r = rng(7);
    for (let i = 0; i < 40; i++) preOf(cid, c.gen(r)).forEach((x) => set.add(x));
  }
  return (preCache[cid] = [...set]);
}
// 숫자와 상관없이 언제나 필요한 앞 개념 (여러 문항의 교집합) — 시뮬레이션·지도 굵은 줄
const coreCache = {};
export function corePre(cid) {
  if (coreCache[cid]) return coreCache[cid];
  const c = byId[cid];
  if (typeof c.pre !== 'function') return (coreCache[cid] = preOf(cid, null));
  const r = rng(11);
  let set = null;
  for (let i = 0; i < 40; i++) { const s = new Set(preOf(cid, c.gen(r))); set = set ? new Set([...set].filter((x) => s.has(x))) : s; }
  return (coreCache[cid] = [...set]);
}
export const nextOf = (cid) => CONCEPTS.filter((c) => allPre(c.id).includes(cid)).map((c) => c.id);

// 문항 하나 만들기 — 개념 id·params가 있으면 언제든 다시 만들 수 있다(이어 하기)
export function makeItem(cid, p) {
  const c = byId[cid];
  const it = c.make(p);
  it.c = cid; it.p = p;
  it.nBlanks = it.choices ? 0 : blankCount(it.prompt);
  it.timed = !!(c.timed && it.timed !== false && it.timed);
  return it;
}
export function genItem(cid, seed) {
  const r = rng(seed), c = byId[cid];
  return makeItem(cid, c.gen(r));
}
export function stepsOf(cid, p) {
  const c = byId[cid];
  return c.steps ? c.steps(p).filter((s) => s && byId[s.c]) : [];
}

// 학년 순서로 정렬 (같은 학년이면 영역 순)
const sOrder = Object.fromEntries(STRANDS.map(([k], i) => [k, i]));
export const sortByGrade = (ids) => ids.slice().sort((a, b) => gradeIdx(byId[a].g) - gradeIdx(byId[b].g) || sOrder[byId[a].s] - sOrder[byId[b].s] || a.localeCompare(b, 'en', { numeric: true }));
