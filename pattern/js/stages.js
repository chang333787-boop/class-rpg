// 판마다 정답(그림 기준) — 화면 · 시험이 같이 쓴다
for (const p of PUZ) {
  p.grid = gridOf(p.motif);
  if (p.move) { p.target = apply(p.grid, p.move); p.answers = answersOfMove(p.motif, p.move); }
  if (p.kind === 'friend') {
    const ok = p.says.map(([, m]) => p.answers.includes(canon(m)));
    p.correct = ok[0] && ok[1] ? 'both' : ok[0] ? 'a' : ok[1] ? 'b' : 'none';
  }
  if (p.kind === 'build' || p.kind === 'fix') p.wall = wallpaper(p.motif, p.unit, p.cols, p.rows);
}
export { PUZ };
export const puzById = id => PUZ.find(p => p.id === id) || null;
export const puzOf = ch => PUZ.filter(p => p.ch === ch);
